#ifndef TOKEN_H
#define TOKEN_H

#include <string>

enum TokenType
{
	// Physical lines
	EOF,
	EOL,

	// Logical lines
	NEW_LINE,

	// Comments
	HASHTAG,

	// Indentation
	INDENT,
	DEDENT,

	// Identifiers
	IDENTIFIER,

	// Literals
	INTEGER,
	STRING,

	// Keywords
	KEYWORD_FALSE,
	KEYWORD_NONE,
	KEYWORD_TRUE,
	KEYWORD_AND,
	KEYWORD_AS,
	KEYWORD_ASSERT,
	KEYWORD_ASYNC,
	KEYWORD_AWAIT,
	KEYWORD_BREAK,
	KEYWORD_CLASS,
	KEYWORD_CONTINUE,
	KEYWORD_DEF,
	KEYWORD_DEL,
	KEYWORD_ELIF,
	KEYWORD_ELSE,
	KEYWORD_EXCEPT,
	KEYWORD_FINALLY,
	KEYWORD_FOR,
	KEYWORD_FROM,
	KEYWORD_GLOBAL,
	KEYWORD_IF,
	KEYWORD_IMPORT,
	KEYWORD_IN,
	KEYWORD_IS,
	KEYWORD_LAMBDA,
	KEYWORD_NONLOCAL,
	KEYWORD_NOT,
	KEYWORD_OR,
	KEYWORD_PASS,
	KEYWORD_RAISE,
	KEYWORD_RETURN,
	KEYWORD_TRY,
	KEYWORD_WHILE,
	KEYWORD_WITH,
	KEYWORD_YIELD,

	// Delimiter
	DELIM_LPAREN,
	DELIM_RPAREN,
	DELIM_LBRACKET,
	DELIM_RBRACKET,
	DELIM_COMMA,
	DELIM_COLON,
	DELIM_DOT,

	// Operator
	OP_PLUS,
	OP_MINUS,
	OP_STAR,
	OP_SLASH_SLASH,
	OP_PERCENT,
	OP_LT,
	OP_GT,
	OP_LE,
	OP_GE,
	OP_EQEQ,
	OP_NEQ,
	OP_ASSIGN,
	OP_ARROW
};

class Token
{
public:
	TokenType token;
	std::string lexeme;
};


#endif